"""Run real source offline tests; never starts the game or connects a mailbox."""
from pathlib import Path
from datetime import datetime, timezone
import json
import os
import subprocess
import sys

SOURCE = Path(__file__).resolve().parents[1]
OUTPUT = Path(os.environ.get('MDC_TEST_OUTPUT', str(SOURCE.parent / 'validation' / 'increment2-python-node')))
OUTPUT.mkdir(parents=True, exist_ok=True)
parts = ['capability-runtime', 'resident-controller', 'navigation-controller', 'navigation-cursor',
         'defense-watchdog', 'gameplay-helpers', 'building-controller', 'external-controller', 'multiagent-coordination']
env = dict(os.environ, PYTHONDONTWRITEBYTECODE='1', WATCHDOG_CANDIDATE=str(SOURCE / 'defense-watchdog'),
           PYTHONPATH=os.pathsep.join(str(SOURCE / p) for p in parts))
# Retained existing native wire fixture was generated by the verified baseline;
# changed native action paths get separate new native tests/current build.
wire = SOURCE.parent / 'baseline-evidence' / 'wire' / 'grass-support-wire.json'
if 'MDC_GRASS_SUPPORT_WIRE' not in env and wire.is_file():
    env['MDC_GRASS_SUPPORT_WIRE'] = str(wire)
commands = [('toolbox-doc-examples', SOURCE, [sys.executable, '-B', 'test-tools/check_toolbox_call_examples.py']),
            ('toolbox-package-integrity', SOURCE, [sys.executable, '-B', 'test-tools/test_package_toolbox_delivery.py'])]
for part in parts:
    sub = '.' if part in ('defense-watchdog', 'building-controller', 'external-controller') else 'tests'
    commands.append((part, SOURCE / part, [sys.executable, '-B', '-m', 'unittest', 'discover', '-s', sub, '-p', 'test*.py', '-v']))
commands.append(('python-toolbox', SOURCE / 'capability-runtime',
                 [sys.executable, '-B', '-m', 'unittest', 'discover', '-s', 'tests/toolbox', '-p', 'test*.py', '-v']))
mcp = SOURCE / 'client-mod' / 'mcp'
commands.extend([('node-portable', mcp, ['node', '--test', 'client-action-test.mjs', 'encounter-contract-test.mjs', 'mainline-client-action-test.mjs', 'boat-transfer-test.mjs', 'encounter-pause-flag-test.mjs', 'three-zombie-contract-test.mjs', 'toolbox-test.mjs', 'toolbox-bridge-recovery-test.mjs', 'toolbox-schema-test.mjs', 'toolbox-owner-chain-test.mjs', 'toolbox-placement-owner-chain-test.mjs', 'defend-once-test.mjs']),
                 ('node-framing', mcp, ['node', 'ndjson-framing-test.mjs']),
                 ('node-platform', mcp, ['node', 'self-test-platform.mjs'])])
results = {'started_utc': datetime.now(timezone.utc).isoformat(), 'scope': 'offline only', 'components': []}
for name, cwd, cmd in commands:
    with (OUTPUT / (name + '.log')).open('w') as log:
        run = subprocess.run(cmd, cwd=cwd, env=env, stdout=log, stderr=subprocess.STDOUT)
    lines = (OUTPUT / (name + '.log')).read_text().splitlines()
    entry = {'component': name, 'exit_code': run.returncode, 'summary': [s for s in lines if s.startswith(('Ran ', 'OK', 'FAILED', '# tests', '# pass', '# fail', '# skipped', 'ℹ tests', 'ℹ pass', 'ℹ fail', 'ℹ skipped', 'SELF_TEST_', 'NDJSON_'))]}
    results['components'].append(entry)
    (OUTPUT / 'RESULTS.json').write_text(json.dumps(results, indent=2) + '\n')
    print(name, run.returncode, ' | '.join(entry['summary']), flush=True)
results['ended_utc'] = datetime.now(timezone.utc).isoformat()
(OUTPUT / 'RESULTS.json').write_text(json.dumps(results, indent=2) + '\n')
raise SystemExit(any(r['exit_code'] for r in results['components']))
